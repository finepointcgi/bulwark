using System.Diagnostics;
using System.Text;
using System.Text.Json.Nodes;
using System.Text.RegularExpressions;
using Bulwark.Core.Findings;
using Bulwark.Core.Fixes;
using Bulwark.Core.Reports;
using Bulwark.Core.Updates;

namespace Bulwark.Cli;

/// <summary>
/// bulwark fix [path] [--dry-run] [--pr] [--min-severity low]
/// Upgrades vulnerable dependencies from the last scan of the project to the smallest version that
/// fixes all their advisories. Uses each ecosystem's own tool where possible (with install scripts
/// disabled). --pr commits to a new branch and opens a pull request with `gh`.
/// </summary>
internal static partial class FixCommand
{
    public static async Task<int> RunAsync(Options options)
    {
        var project = Path.GetFullPath(options.Positional.ElementAtOrDefault(0) ?? ".");
        var home = ManifestStore.Default().HomeDirectory;
        var report = new ReportArchive(home).LoadAll().FirstOrDefault(r => r.Project == project)
            ?? throw new ArgumentException($"no scan report for {project}. Run `bulwark scan` there first.");

        var minimum = Enum.Parse<Severity>(options.Value("min-severity") ?? "low", ignoreCase: true);
        var plan = FixPlanner.Plan(report.Findings, minimum);
        plan = plan with { Fixes = await VerifyTargetsAsync(plan.Fixes) };
        foreach (var (finding, reason) in plan.Unfixable)
        {
            Console.Error.WriteLine($"  cannot fix {finding.RuleId} in {finding.Package?.Name}@{finding.Package?.Version}: {reason}");
        }

        if (plan.Fixes.Count == 0)
        {
            Console.WriteLine("No dependency upgrades available.");
            return 0;
        }

        Console.WriteLine($"{plan.Fixes.Count} upgrade(s):");
        foreach (var fix in plan.Fixes)
        {
            Console.WriteLine($"  {fix.WorstSeverity,-8} {fix.Package.Ecosystem,-9} {fix.Package.Name} {fix.Package.Version} → {fix.TargetVersion}  ({string.Join(", ", fix.Advisories)})");
        }

        if (options.Has("dry-run"))
        {
            return 0;
        }

        string? branch = null;
        if (options.Has("pr"))
        {
            EnsureCleanTree(project);
            branch = $"bulwark/fix-dependencies-{DateTime.UtcNow:yyyyMMdd-HHmm}";
            Run(project, "git", "checkout", "-b", branch);
        }

        var applied = new List<DependencyFix>();
        foreach (var fix in plan.Fixes)
        {
            try
            {
                if (await ApplyAsync(project, fix))
                {
                    applied.Add(fix);
                    Console.WriteLine($"  ✓ {fix.Package.Name} → {fix.TargetVersion}");
                }
                else
                {
                    Console.Error.WriteLine($"  - {fix.Package.Name}: no automatic fixer for {fix.Package.Ecosystem} ({fix.ManifestPath}); upgrade it by hand");
                }
            }
            catch (Exception e) when (e is InvalidOperationException or IOException or System.ComponentModel.Win32Exception)
            {
                Console.Error.WriteLine($"  ✗ {fix.Package.Name}: {e.Message}");
            }
        }

        if (branch is null || applied.Count == 0)
        {
            Console.WriteLine(applied.Count == 0 ? "Nothing was changed." : "Changes are in your working tree. Rebuild and run your tests, then rescan.");
            return applied.Count == plan.Fixes.Count ? 0 : 1;
        }

        Run(project, "git", "add", "-A");
        Run(project, "git", "commit", "-m", $"Upgrade {applied.Count} vulnerable dependenc{(applied.Count == 1 ? "y" : "ies")}\n\nGenerated by bulwark fix.");
        Run(project, "git", "push", "-u", "origin", branch);
        var body = PullRequestBody(applied, plan);
        var bodyFile = Path.GetTempFileName();
        await File.WriteAllTextAsync(bodyFile, body);
        try
        {
            Console.WriteLine(Run(project, "gh", "pr", "create", "--title", $"Upgrade {applied.Count} vulnerable dependenc{(applied.Count == 1 ? "y" : "ies")}", "--body-file", bodyFile, "--head", branch).Trim());
        }
        finally
        {
            File.Delete(bodyFile);
        }

        return 0;
    }

    /// <summary>
    /// The planned version may have advisories of its own (published for that version only). Ask OSV
    /// about the target and step up to its fixes until it is clean, so a fix PR never ships a new CVE.
    /// </summary>
    private static async Task<IReadOnlyList<DependencyFix>> VerifyTargetsAsync(IReadOnlyList<DependencyFix> fixes)
    {
        using var http = new HttpClient { Timeout = TimeSpan.FromSeconds(30) };
        http.DefaultRequestHeaders.UserAgent.ParseAdd("bulwark-fix");
        var verified = new List<DependencyFix>();
        foreach (var fix in fixes)
        {
            var target = fix.TargetVersion;
            for (var attempt = 0; attempt < 5; attempt++)
            {
                var next = await NextCleanVersionAsync(http, fix.Package, target);
                if (next is null || next == target)
                {
                    break;
                }

                Console.Error.WriteLine($"  {fix.Package.Name} {target} has its own advisories; trying {next}");
                target = next;
            }

            verified.Add(fix with { TargetVersion = target });
        }

        return verified;
    }

    /// <summary>Null or the same version when OSV knows no advisory for it; otherwise the smallest version fixing them all.</summary>
    private static async Task<string?> NextCleanVersionAsync(HttpClient http, PackageRef package, string version)
    {
        try
        {
            using var response = await http.PostAsync("https://api.osv.dev/v1/query", new StringContent(
                new JsonObject
                {
                    ["version"] = version,
                    ["package"] = new JsonObject { ["name"] = package.Name, ["ecosystem"] = package.Ecosystem },
                }.ToJsonString(), Encoding.UTF8, "application/json"));
            response.EnsureSuccessStatusCode();
            var vulns = JsonNode.Parse(await response.Content.ReadAsStringAsync())?["vulns"]?.AsArray();
            if (vulns is null || vulns.Count == 0)
            {
                return null;
            }

            var findings = vulns.OfType<JsonObject>().Select(v => new Finding
            {
                Id = v["id"]!.GetValue<string>(),
                Category = FindingCategory.Vulnerability,
                Severity = Severity.Unknown,
                RuleId = v["id"]!.GetValue<string>(),
                Title = "",
                Package = package with { Version = version },
                FixedVersions = (v["affected"]?.AsArray() ?? [])
                    .Where(a => string.Equals(a?["package"]?["name"]?.GetValue<string>(), package.Name, StringComparison.OrdinalIgnoreCase))
                    .SelectMany(a => a?["ranges"]?.AsArray() ?? [])
                    .SelectMany(r => r?["events"]?.AsArray() ?? [])
                    .Select(e => e?["fixed"]?.GetValue<string>()).OfType<string>().ToList(),
            });

            return FixPlanner.Plan(findings, Severity.Unknown).Fixes.FirstOrDefault()?.TargetVersion;
        }
        catch (Exception e) when (e is HttpRequestException or TaskCanceledException or System.Text.Json.JsonException)
        {
            Console.Error.WriteLine($"  could not verify {package.Name}@{version} against OSV ({e.Message}); using it as planned");
            return null;
        }
    }

    private static async Task<bool> ApplyAsync(string project, DependencyFix fix)
    {
        var manifest = fix.ManifestPath is { } m ? Path.Combine(project, m) : null;
        var directory = manifest is not null ? Path.GetDirectoryName(manifest)! : project;
        var name = fix.Package.Name;
        var version = fix.TargetVersion;

        switch (fix.Package.Ecosystem)
        {
            case "npm":
            {
                var packageJson = Path.Combine(directory, "package.json");
                if (!File.Exists(packageJson))
                {
                    return false;
                }

                var root = JsonNode.Parse(await File.ReadAllTextAsync(packageJson))!.AsObject();
                var spec = new[] { "dependencies", "devDependencies", "optionalDependencies" }
                    .Select(section => root[section]?[name]?.GetValue<string>())
                    .FirstOrDefault(s => s is not null);
                if (spec is not null)
                {
                    // Keep the project's pinning style: an exact pin stays exact.
                    var exact = spec.Length > 0 && char.IsDigit(spec[0]);
                    Run(directory, "npm", ["install", $"{name}@{version}", "--package-lock-only", "--ignore-scripts", "--no-audit", "--no-fund",
                        .. exact ? new[] { "--save-exact" } : []]);
                }
                else
                {
                    // Transitive: pin it with npm overrides instead of adding a new direct dependency.
                    var overrides = root["overrides"] as JsonObject ?? new JsonObject();
                    overrides[name] = version;
                    root["overrides"] = overrides;
                    await File.WriteAllTextAsync(packageJson, root.ToJsonString(new System.Text.Json.JsonSerializerOptions { WriteIndented = true }) + "\n");
                    Run(directory, "npm", "install", "--package-lock-only", "--ignore-scripts", "--no-audit", "--no-fund");
                }

                return true;
            }

            case "NuGet":
            {
                // Direct or transitive, a PackageReference at the fixed version is how NuGet overrides it.
                var projects = Directory.EnumerateFiles(directory, "*.csproj", SearchOption.TopDirectoryOnly)
                    .Concat(Directory.EnumerateFiles(directory, "*.fsproj", SearchOption.TopDirectoryOnly)).ToList();
                if (projects.Count == 0)
                {
                    return false;
                }

                foreach (var csproj in projects)
                {
                    Run(directory, "dotnet", "add", csproj, "package", name, "--version", version, "--no-restore");
                }

                return true;
            }

            case "PyPI" when manifest is not null && Path.GetFileName(manifest).StartsWith("requirements", StringComparison.OrdinalIgnoreCase):
            {
                var text = await File.ReadAllTextAsync(manifest);
                var updated = Regex.Replace(text, $@"(?im)^(\s*{Regex.Escape(name)}\s*(?:\[[^\]]*\])?\s*)==\s*[^\s;#]+", $"${{1}}=={version}");
                if (updated == text)
                {
                    return false; // Not an exact pin; leave ranges to a human.
                }

                await File.WriteAllTextAsync(manifest, updated);
                return true;
            }

            case "Go":
            {
                Run(directory, "go", "get", $"{name}@v{version.TrimStart('v')}");
                Run(directory, "go", "mod", "tidy");
                return true;
            }

            default:
                return false;
        }
    }

    private static string PullRequestBody(IReadOnlyList<DependencyFix> applied, FixPlan plan)
    {
        var body = new StringBuilder("Bulwark found known vulnerabilities in these dependencies and upgraded each to the smallest version that fixes all of them.\n\n");
        body.AppendLine("| Package | From | To | Fixes | Worst |\n|---|---|---|---|---|");
        foreach (var fix in applied)
        {
            body.AppendLine($"| `{fix.Package.Name}` ({fix.Package.Ecosystem}) | {fix.Package.Version} | **{fix.TargetVersion}** | {string.Join(", ", fix.Advisories)} | {fix.WorstSeverity} |");
        }

        if (plan.Unfixable.Count > 0)
        {
            body.AppendLine($"\n{plan.Unfixable.Count} advisor{(plan.Unfixable.Count == 1 ? "y has" : "ies have")} no fixed version yet and need another mitigation.");
        }

        body.AppendLine("\nPlease run the build and tests before merging: even small upgrades can change behavior.");
        return body.ToString();
    }

    private static void EnsureCleanTree(string project)
    {
        if (Run(project, "git", "status", "--porcelain").Trim().Length > 0)
        {
            throw new InvalidOperationException("the working tree has uncommitted changes; commit or stash them before `bulwark fix --pr`");
        }
    }

    private static string Run(string directory, string file, params string[] args)
    {
        var start = new ProcessStartInfo(file) { WorkingDirectory = directory, RedirectStandardOutput = true, RedirectStandardError = true };
        foreach (var arg in args)
        {
            start.ArgumentList.Add(arg);
        }

        using var process = Process.Start(start) ?? throw new InvalidOperationException($"could not start {file}");
        var stdout = process.StandardOutput.ReadToEndAsync();
        var stderr = process.StandardError.ReadToEnd();
        process.WaitForExit();
        if (process.ExitCode != 0)
        {
            throw new InvalidOperationException($"{file} {string.Join(' ', args)} failed: {stderr.Trim()}");
        }

        return stdout.Result;
    }
}
